/**
 * Output/input path policy for the Office editor tools: absolute-path resolution against
 * the session working directory, write-to-new-file by default, in-place writes with an
 * automatic `.bak` backup, and restore-on-write-failure.
 * @module dsh-office-editor/src/io
 */

import { copyFile, mkdir, readFile, stat, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import type { ToolExecution } from '@deepseek-ai/dsh-tools'

/** Deployment caps shared by the editor tools (resolved plugin config). */
export interface EditorCaps {
  /** Maximum input document size in bytes. */
  maxInputBytes: number
  /** Maximum written document size in bytes. */
  maxOutputBytes: number
}

/**
 * Resolve a model-supplied path (absolute, file:// URL, or relative to the session working
 * directory) to an absolute local path.
 * @param exec - the tool execution supplying the session cwd.
 * @param path - the model-supplied path.
 * @param label - parameter name used in error messages (e.g. "output").
 * @returns the absolute local path.
 * @throws an Error with a user-facing Chinese message on empty input or unsupported schemes.
 */
export function resolveLocal(exec: ToolExecution, path: string, label: string): string {
  const trimmed = path.trim()
  if (trimmed === '') throw new Error(`${label} 参数不能为空`)
  if (/^https?:\/\//i.test(trimmed)) {
    throw new Error(`${label} 暂不支持 http(s) 链接，请提供本地文件路径`)
  }
  const unwrapped = /^file:\/\//i.test(trimmed) ? fileURLToPath(trimmed) : trimmed
  const cwd = exec.agent?.session.header.cwd ?? process.cwd()
  return resolve(cwd, unwrapped)
}

/**
 * Read an input document with the size cap applied.
 * @param absolute - absolute local path.
 * @param caps - resolved deployment caps.
 * @returns the raw document bytes.
 * @throws an Error when the file is missing or oversized.
 */
export async function readInput(absolute: string, caps: EditorCaps): Promise<Uint8Array> {
  let size: number
  try {
    size = (await stat(absolute)).size
  } catch {
    // stat failure here means the input does not exist (or is unreadable) — report that directly.
    throw new Error(`找不到文件：${absolute}（请确认路径正确）`)
  }
  if (size > caps.maxInputBytes) {
    throw new Error(`文件过大（${Math.round(size / 1024 / 1024)}MB），超过上限 ${Math.round(caps.maxInputBytes / 1024 / 1024)}MB`)
  }
  return new Uint8Array(await readFile(absolute))
}

/** Result of a successful write. */
export interface WriteOutcome {
  /** Absolute path the bytes were written to. */
  target: string
  /** Absolute path of the automatic `.bak` backup, present only for in-place writes. */
  backup?: string
}

/**
 * Write generated bytes to `absolute`. An existing target requires `inPlace`; in-place
 * writes copy the previous content to `${absolute}.bak` first and restore it if the
 * write itself fails. The bytes are expected to be verified by the caller before this runs.
 * @param absolute - absolute target path.
 * @param bytes - document bytes to write.
 * @param inPlace - whether overwriting an existing file is allowed.
 * @param maxBytes - maximum allowed output size in bytes.
 * @returns the write outcome including the backup path when one was created.
 * @throws an Error when the target exists without `inPlace`, is oversized, or the write fails.
 */
export async function writeOutput(absolute: string, bytes: Uint8Array, inPlace: boolean, maxBytes: number): Promise<WriteOutcome> {
  if (bytes.byteLength > maxBytes) {
    throw new Error(`生成内容过大（${Math.round(bytes.byteLength / 1024 / 1024)}MB），超过上限 ${Math.round(maxBytes / 1024 / 1024)}MB`)
  }
  let exists = false
  try {
    await stat(absolute)
    exists = true
  } catch {
    // stat failure means the target does not exist yet — proceed with a fresh create.
  }
  if (exists && !inPlace) {
    throw new Error(`目标文件已存在：${absolute}（如需覆盖请设 in_place=true，会自动备份 .bak；或换一个输出路径）`)
  }
  let backup: string | undefined
  if (exists) {
    backup = `${absolute}.bak`
    await copyFile(absolute, backup)
  }
  try {
    await mkdir(dirname(absolute), { recursive: true })
    await writeFile(absolute, bytes)
  } catch (error) {
    // Restore the backup so an in-place edit never leaves a half-written file behind.
    if (backup !== undefined) await copyFile(backup, absolute)
    throw error
  }
  return { target: absolute, backup }
}
