/**
 * Output path policy for the PDF editor: absolute-path resolution against the session working
 * directory, write-to-new-file by default, in-place writes with an automatic `.bak` backup,
 * restore-on-write-failure, and a per-file name sanitizer for derived output names.
 * @module dsh-pdf-editor/src/io
 */

import { copyFile, mkdir, readFile, stat, writeFile } from 'node:fs/promises'
import { basename, dirname, extname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import type { ToolExecution } from '@deepseek-ai/dsh-tools'

/** Deployment caps for writing (resolved plugin config). */
export interface OutputCaps {
  /** Maximum written file size in bytes. */
  maxOutputBytes: number
}

/** Result of a successful write. */
export interface WriteOutcome {
  /** Absolute path the bytes were written to. */
  target: string
  /** Absolute path of the automatic `.bak` backup, present only when an existing file was overwritten. */
  backup?: string
}

/**
 * Resolve a model-supplied output path to an absolute local path.
 * @param exec - the tool execution supplying the session cwd.
 * @param path - the model-supplied path.
 * @param label - parameter name used in error messages (e.g. "output").
 * @returns the absolute local path.
 * @throws an Error with a user-facing Chinese message on empty input or an http(s) URL.
 */
export function resolveOutput(exec: ToolExecution, path: string, label: string): string {
  const trimmed = path.trim()
  if (trimmed === '') throw new Error(`${label} 参数不能为空`)
  if (/^https?:\/\//i.test(trimmed)) throw new Error(`${label} 必须是本地路径，不支持 http(s) 链接`)
  const unwrapped = /^file:\/\//i.test(trimmed) ? fileURLToPath(trimmed) : trimmed
  const cwd = exec.agent?.session.header.cwd ?? process.cwd()
  return resolve(cwd, unwrapped)
}

/** Resolve and create an output directory. */
export async function resolveOutDir(exec: ToolExecution, path: string, label: string): Promise<string> {
  const absolute = resolveOutput(exec, path, label)
  await mkdir(absolute, { recursive: true })
  return absolute
}

/** Strip the extension from an absolute path (the file name without `.pdf`). */
export function stemOf(absolute: string): string {
  const name = basename(absolute)
  const ext = extname(name)
  return ext === '' ? name : name.slice(0, -ext.length)
}

/** Directory containing an absolute path. */
export function dirOf(absolute: string): string {
  return dirname(absolute)
}

/** Derive a sibling output path: `<dir>/<stem><suffix>.pdf`. */
export function deriveOutput(sourceAbsolute: string, suffix: string): string {
  return join(dirOf(sourceAbsolute), `${stemOf(sourceAbsolute)}${suffix}.pdf`)
}

/** Replace the characters Windows forbids in a file name. */
export function sanitizeFileName(name: string): string {
  const cleaned = name.replace(/[\\/:*?"<>|\u0000-\u001f]/gu, '_').replace(/[. ]+$/gu, '').trim()
  return cleaned === '' ? 'part' : cleaned.slice(0, 80)
}

/**
 * Write generated bytes to `absolute`. An existing target requires `inPlace`; overwriting copies
 * the previous content to `${absolute}.bak` first and restores it if the write itself fails.
 * The caller verifies the bytes before this runs.
 * @param absolute - absolute target path.
 * @param bytes - PDF bytes to write.
 * @param inPlace - whether overwriting an existing file is allowed.
 * @param maxBytes - maximum allowed output size in bytes.
 * @returns the write outcome including the backup path when one was created.
 * @throws an Error when the target exists without `inPlace`, is oversized, or the write fails.
 */
export async function writeOutput(absolute: string, bytes: Uint8Array, inPlace: boolean, maxBytes: number): Promise<WriteOutcome> {
  if (bytes.byteLength > maxBytes) {
    throw new Error(`生成内容过大（${Math.round(bytes.byteLength / 1024 / 1024)}MB），超过上限 ${Math.round(maxBytes / 1024 / 1024)}MB`)
  }
  let exists = false
  try {
    await stat(absolute)
    exists = true
  } catch {
    // stat failure means the target does not exist yet — proceed with a fresh create.
  }
  if (exists && !inPlace) {
    throw new Error(`目标文件已存在：${absolute}（如需覆盖请设 in_place=true，会自动备份 .bak；或换一个输出路径）`)
  }
  let backup: string | undefined
  if (exists) {
    backup = `${absolute}.bak`
    await copyFile(absolute, backup)
  }
  try {
    await mkdir(dirname(absolute), { recursive: true })
    await writeFile(absolute, bytes)
  } catch (error) {
    // Restore the backup so an in-place edit never leaves a half-written file behind.
    if (backup !== undefined) await copyFile(backup, absolute)
    throw error
  }
  return backup === undefined ? { target: absolute } : { target: absolute, backup }
}

/** Read an image file for stamping, with the byte cap applied. */
export async function readImageFile(absolute: string, maxBytes: number): Promise<Uint8Array> {
  let size: number
  try {
    size = (await stat(absolute)).size
  } catch {
    throw new Error(`找不到图片文件：${absolute}`)
  }
  if (size > maxBytes) {
    throw new Error(`图片过大（${Math.round(size / 1024 / 1024)}MB），超过上限 ${Math.round(maxBytes / 1024 / 1024)}MB`)
  }
  return new Uint8Array(await readFile(absolute))
}
